#!/usr/bin/env node
// Writes test/token-budget.json: how much text the server's tool list costs a client.
//
// A client sends each tool's name, description and input schema to the model with every
// request, before the user has asked anything. Some clients send the output schema and
// annotations too. The server instructions are also sent on every request. This script asks
// the built server for its tools over stdio, in full and in read-only mode, and records the
// size of each part in characters of compact JSON.
//
// Sizes are characters, not tokens: they are exact, need no tokenizer, and come out the same
// on every machine. Tokens depend on the client's model. As a rough guide, JSON costs about
// one token for every 3 to 4 characters.
//
// The file is committed, and CI fails when it no longer matches the server, so a change to
// a description or schema shows its cost in the pull request's diff.
//
// Usage (after `npm run build`):
//   node scripts/token-budget.mjs          rewrite test/token-budget.json
//   node scripts/token-budget.mjs --check  exit 1 if test/token-budget.json is out of date

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outPath = join(root, 'test', 'token-budget.json');
const check = process.argv.includes('--check');

async function listTools(readOnly) {
  // Tools register without a reachable Uptime Kuma: the initial login failure is not fatal.
  // A closed local port fails fast instead of waiting on a network timeout.
  const transport = new StdioClientTransport({
    command: process.execPath,
    args: [join(root, 'dist', 'index.js'), '-t', 'stdio'],
    env: {
      ...process.env,
      UPTIME_KUMA_URL: 'http://127.0.0.1:9',
      UPTIME_KUMA_READ_ONLY: readOnly ? 'true' : '',
      UPTIME_KUMA_TOOLSETS: '',
    },
    stderr: 'ignore',
  });
  const client = new Client({ name: 'token-budget', version: '1.0.0' });
  await client.connect(transport);
  const tools = [];
  let cursor;
  do {
    const page = await client.listTools(cursor ? { cursor } : {});
    tools.push(...page.tools);
    cursor = page.nextCursor;
  } while (cursor);
  const instructions = client.getInstructions() ?? '';
  await client.close();
  return { tools, instructions };
}

const size = (value) => (value === undefined ? 0 : JSON.stringify(value).length);

function measureTool(tool) {
  const { name, description, inputSchema, outputSchema, annotations, ...rest } = tool;
  return {
    // What every client sends to the model: the name, description and input schema.
    core: size({ name, description, inputSchema }),
    description: (description ?? '').length,
    inputSchema: size(inputSchema),
    outputSchema: size(outputSchema),
    annotations: size(annotations),
    // Everything tools/list carries for the tool, including fields such as title.
    advertised: size({ name, description, inputSchema, outputSchema, annotations, ...rest }),
  };
}

function measureMode({ tools, instructions }) {
  const perTool = Object.fromEntries(
    tools
      .slice()
      .sort((a, b) => a.name.localeCompare(b.name))
      .map((tool) => [tool.name, measureTool(tool)])
  );
  const sum = (key) => Object.values(perTool).reduce((total, t) => total + t[key], 0);
  const totals = {
    tools: tools.length,
    instructions: instructions.length,
    core: sum('core'),
    description: sum('description'),
    inputSchema: sum('inputSchema'),
    outputSchema: sum('outputSchema'),
    annotations: sum('annotations'),
    advertised: sum('advertised'),
  };
  // The least a client can send per request (core plus instructions), and the most.
  totals.perRequestMin = totals.core + totals.instructions;
  totals.perRequestMax = totals.advertised + totals.instructions;
  return { totals, perTool };
}

const all = measureMode(await listTools(false));
const readOnly = measureMode(await listTools(true));

const budget = {
  $comment:
    'Generated by scripts/token-budget.mjs; do not edit. Sizes are characters of compact JSON. ' +
    'core = name + description + inputSchema, which every client sends to the model. ' +
    'advertised = everything tools/list carries, which some clients send in full.',
  all: all.totals,
  readOnly: readOnly.totals,
  tools: all.perTool,
};

const json = `${JSON.stringify(budget, null, 2)}\n`;
const summary =
  `${all.totals.tools} tools: ${all.totals.perRequestMin} to ${all.totals.perRequestMax} characters per request ` +
  `(read-only: ${readOnly.totals.tools} tools, ${readOnly.totals.perRequestMin} to ${readOnly.totals.perRequestMax})`;

if (check) {
  let current = '';
  try {
    current = readFileSync(outPath, 'utf8');
  } catch {
    /* missing counts as stale */
  }
  if (current !== json) {
    let before;
    try {
      before = JSON.parse(current).all;
    } catch {
      /* nothing to compare against */
    }
    console.error('test/token-budget.json is out of date. Run: npm run token-budget');
    if (before) {
      for (const key of ['tools', 'perRequestMin', 'perRequestMax']) {
        if (before[key] !== all.totals[key]) console.error(`  ${key}: ${before[key]} -> ${all.totals[key]}`);
      }
    }
    process.exit(1);
  }
  console.log(`token-budget.json is up to date. ${summary}`);
} else {
  writeFileSync(outPath, json);
  console.log(`Wrote test/token-budget.json. ${summary}`);
}
